#!/usr/bin/env python3
"""Build a ComfyUI UI workflow .json from a compact node/link spec.

Why this exists: `2d/workflows/pbr-material.json` was machine-generated by a throwaway script that stamped
`order = node id` for every node and counted the MarkdownNote in. The ComfyUI frontend could then not
attribute the workflow's nodes to a pack, and offered them as an install prompt ("Unknown pack:
MarigoldModelLoader ...") - which reads exactly like a missing pack even though every node loaded fine and
`/prompt` accepted the graph. Hand-editing these files is also where the earlier stale-id bug
(`fix_workflow_links.py`) came from, so generation is worth doing once, carefully.

The rules this encodes (each one learned from a shipped bug):
  * **commentary nodes are never numbered.** A `MarkdownNote`/`Note` gets `order: 0` and no execution slot.
    `scripts/lint_docs.py::check_workflow_order` enforces it.
  * **execution nodes are numbered 0..N-1** in the order they are listed, so a rebuild is deterministic.
  * **every node carries `properties["Node name for S&R"]`** - ComfyUI uses it for the node title.
  * **links are declared once** and the per-node `outputs[].links` / `inputs[].link` are derived from them,
    so the two views cannot disagree (that is what `scripts/fix_workflow_links.py` repairs elsewhere).

Usage:  uv run python scripts/build_workflow.py --spec <spec.py> --out <file.json>

The spec is a Python file defining `NODES`, `LINKS` and `NOTE` (or `NOTE = None`); see
`--spec 2d/workflows/pbr-material.json`'s original spec in the commit that introduced this tool, or write
one with the same shape: NODES is a list of dicts with id/type/pos/widgets/inputs/outputs/title, LINKS a
list of [id, from_node, from_slot, to_node, to_slot, type].
"""
from __future__ import annotations

import argparse
import importlib.util
import json
import os
import sys

COMMENTARY = ("MarkdownNote", "Note")


def load_spec(path):
    spec = importlib.util.spec_from_file_location("wf_spec", path)
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod


def build(mod) -> dict:
    order = 0
    nodes = []
    for raw in mod.NODES:
        n = {k: v for k, v in raw.items()}
        n.setdefault("flags", {})
        n.setdefault("mode", 0)
        n.setdefault("size", [270, 100])
        n.setdefault("inputs", [])
        n.setdefault("outputs", [])
        n.setdefault("widgets_values", [])
        n["properties"] = {"Node name for S&R": n["type"]}
        if n["type"] in COMMENTARY:
            n["order"] = 0
        else:
            n["order"] = order
            order += 1
        nodes.append(n)

    comment = [n for n in nodes if n["type"] in COMMENTARY]
    if mod.NOTE is not None:
        if not comment:
            raise SystemExit("spec defines NOTE but no MarkdownNote node")
        comment[0]["widgets_values"] = [mod.NOTE]
        comment[0]["size"] = [420, 320]
        comment[0]["properties"] = {}

    # derive the two link views from LINKS, so they cannot drift
    links = [list(l) for l in mod.LINKS]
    by_id = {n["id"]: n for n in nodes}
    for n in nodes:
        for o in n["outputs"]:
            o["links"] = []
    for l in links:
        lid, src, sslot, dst, dslot = l[0], l[1], l[2], l[3], l[4]
        if src not in by_id or dst not in by_id:
            raise SystemExit(f"link {lid} references a node that is not in NODES ({src} -> {dst})")
        outs = by_id[src]["outputs"]
        if sslot >= len(outs):
            raise SystemExit(f"link {lid}: node {src} ({by_id[src]['type']}) has no output slot {sslot}")
        outs[sslot]["links"].append(lid)
        ins = by_id[dst]["inputs"]
        if dslot >= len(ins):
            raise SystemExit(f"link {lid}: node {dst} ({by_id[dst]['type']}) has no input slot {dslot}")
        ins[dslot]["link"] = lid

    return {
        "last_node_id": max(n["id"] for n in nodes),
        "last_link_id": max((l[0] for l in links), default=0),
        "nodes": nodes,
        "links": links,
        "groups": [],
        "config": {},
        "extra": {"ds": {"scale": 0.7, "offset": [0, 0]}},
        "version": 0.4,
    }


def main() -> int:
    ap = argparse.ArgumentParser(description="Build a ComfyUI UI workflow from a spec.")
    ap.add_argument("--spec", required=True)
    ap.add_argument("--out", required=True)
    a = ap.parse_args()
    wf = build(load_spec(a.spec))
    out = os.path.abspath(a.out)
    os.makedirs(os.path.dirname(out), exist_ok=True)
    with open(out, "w", encoding="utf-8", newline="\n") as fh:
        json.dump(wf, fh, indent=1, ensure_ascii=False)
    notes = [n for n in wf["nodes"] if n["type"] in COMMENTARY]
    execs = [n for n in wf["nodes"] if n["type"] not in COMMENTARY]
    print(f"wrote {out}")
    print(f"  {len(execs)} execution nodes (order 0..{len(execs) - 1}), "
          f"{len(notes)} commentary node(s) at order 0, {len(wf['links'])} links")
    return 0


if __name__ == "__main__":
    sys.exit(main())
